/*
    Literais:

        Literais são dados que aparecem diretamento no programa.
        ex.:
        'Olá Mundo!'                string literal
        23                          literal numérico 
        true                        literal booleano
        null                        null literal
        let a = [0,1,2,3]           array literal
        let o = {nome: 'Moisés'}    objeto literal
*/

/*
    Identificadores e palavras reservadas:

        Identificados são os nomes que nós programadores damos as nossas contantes, variáveis, propriedade, funções, classes e também para forncer os rótulos dos laçoes de repetição
        Um identificador em JavaScript deve começar com uma letra, um sublinhado (_) ou um cifrão ($), os demais caracteres que formam o identificar pode ser letras, dígitos, sublinhados ou cifrões
        Um identificado não pode ser nomeado com as palavras reservadas da linguagem

        Palavras reservadas:
            - As palavras reservadas são identificadores que JavaScript já utiliza.
*/


/*
    Ponto e vírgula:

        JavaScript utiliza o ponto e virgula (;) para separar suas instruções, isso é improtante para deixar claro o significado do código
        Em JavaScript normalmente é possível omitir o ponto e vírgula do fim de uma instrução, mas o interpretador de código JavaScript pode entender seu código diferente do esperado em alguns casos por isso sempre defina onde deseja ecerrar suas intruções
*/


